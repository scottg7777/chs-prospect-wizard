"""Browser end-to-end run + review screenshots. Usage: python tests/ui_e2e.py BASE_URL [--keep-invite-name NAME]"""
import re, sys, os, json
from playwright.sync_api import sync_playwright
BASE = sys.argv[1].rstrip("/")
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "screenshots-review")
pw_ = dict(l.strip().split("=", 1) for l in open(os.path.join(os.path.dirname(OUT), ".secrets", "admin.env")) if "=" in l)["ADMIN_PASSWORD"]
prefix = sys.argv[2] if len(sys.argv) > 2 else "local"
errors = []
with sync_playwright() as p:
    b = p.chromium.launch()
    rep = b.new_context(viewport={"width": 1280, "height": 900})
    rp = rep.new_page(); rp.on("console", lambda m: m.type == "error" and errors.append("rep: " + m.text))
    rp.goto(BASE + "/rep"); rp.fill("#pw", pw_); rp.click("#login-form button")
    rp.wait_for_selector("#dash:not(.hidden)")
    rp.fill("#i-pn", "Dr. Taylor Test (TEST)"); rp.fill("#i-pe", "scottg@continuant.com"); rp.fill("#i-pr", "Test Behavioral Health (TEST)")
    rp.fill("#i-rn", "Scott Graham"); rp.fill("#i-re", "scottg@continuant.com"); rp.check("#i-test")
    rp.click("#invite-form button[type=submit]"); rp.wait_for_selector("#new-result:not(.hidden)")
    link = rp.inner_text("#lk").strip()
    rp.screenshot(path=f"{OUT}/{prefix}-01-rep-new-invite.png", full_page=False)
    m = b.new_context(viewport={"width": 414, "height": 860}, device_scale_factor=2, is_mobile=True, has_touch=True)
    pg = m.new_page(); pg.on("console", lambda m_: m_.type == "error" and errors.append("wiz: " + m_.text))
    pg.goto(link); pg.wait_for_selector("text=Let's go")
    pg.wait_for_timeout(700); pg.screenshot(path=f"{OUT}/{prefix}-02-welcome.png", full_page=False)
    pg.click("text=Let's go"); pg.wait_for_selector("#state-grid")
    pg.fill("#state-filter", "ari"); pg.click("[data-state=AZ]"); pg.fill("#state-filter", ""); pg.click("[data-state=TX]")
    pg.wait_for_timeout(700); pg.screenshot(path=f"{OUT}/{prefix}-03-states.png", full_page=False)
    pg.click("#next"); pg.wait_for_selector(".payer")
    for name in ["Medicare Arizona Part B", "AZ Blue", "Aetna", "Medicaid Texas - Acute"]:
        pg.locator(".payer", has_text=name).first.locator("input[type=checkbox]").check()
        pg.wait_for_timeout(150)
    pg.locator("[data-innet]").filter(has_text="Yes").first.click()
    pg.fill("#payer-q", "ambetter"); pg.wait_for_timeout(700)
    if pg.locator("#payer-suggest button[data-addpayer]").count(): pg.locator("#payer-suggest button[data-addpayer]").first.click()
    pg.wait_for_timeout(300); pg.evaluate("window.scrollTo(0,0)")
    pg.wait_for_timeout(700); pg.screenshot(path=f"{OUT}/{prefix}-04-payers.png", full_page=False)
    pg.click("#next"); pg.wait_for_selector("[data-bind='practice.legal_name']")
    pg.fill("[data-bind='practice.legal_name']", "Test Behavioral Health PLLC")
    pg.click("[data-unsure='practice.dba']")
    pg.type("[data-tin]", "123456789"); pg.type("[data-npi='practice.group_npi']", "1234567893")
    pg.wait_for_timeout(700); pg.screenshot(path=f"{OUT}/{prefix}-05-practice.png", full_page=False)
    pg.click("#next"); pg.wait_for_selector("#spec-q")
    pg.type("#spec-q", "psych"); pg.click("#spec-suggest button >> nth=0")
    pg.click("[data-choice='specialty.practice_stage'][data-value=new]"); pg.click("[data-choice='specialty.care_setting'][data-value=both]")
    pg.click("#next"); pg.wait_for_selector("[data-action=count-inc]")
    pg.click("[data-action=count-inc]"); pg.click("[data-action=count-inc]")
    pg.fill("[data-bind='providers.list.0.name']", "Jordan Rivers"); pg.select_option("[data-bind='providers.list.0.credential']", "PMHNP")
    pg.fill("[data-bind='providers.list.1.name']", "Casey Lane"); pg.select_option("[data-bind='providers.list.1.credential']", "LCSW")
    pg.click("[data-seg='providers.list.0.new_to_credentialing'][data-value=yes]")
    pg.wait_for_timeout(300)
    pg.wait_for_timeout(700); pg.evaluate("window.scrollTo(0,0)"); pg.wait_for_timeout(400); pg.screenshot(path=f"{OUT}/{prefix}-06-providers.png", full_page=False)
    pg.click("#next"); pg.wait_for_selector("[data-multi='rcm.services']")
    pg.click("[data-multi='rcm.services'][data-value=credentialing]"); pg.click("[data-multi='rcm.services'][data-value=rcm]")
    pg.click("[data-choice='rcm.billing_setup'][data-value=none]"); pg.type("[data-ehr]", "simple"); pg.click("#ehr-suggest button >> nth=0")
    pg.click("[data-choice='rcm.monthly_claims'][data-value=unsure]"); pg.click("[data-choice='rcm.go_live'][data-value='1-3m']")
    pg.wait_for_timeout(700); pg.screenshot(path=f"{OUT}/{prefix}-07-billing.png", full_page=False)
    # resume test: reload mid-way, ensure answers persisted
    pg.wait_for_timeout(1200); pg.reload(); pg.wait_for_selector("[data-multi='rcm.services']")
    assert pg.get_attribute("[data-multi='rcm.services'][data-value=rcm]", "aria-pressed") == "true", "resume failed"
    pg.click("#next"); pg.wait_for_selector("[data-bind='contact.name']"); pg.click("#skip")  # skip contact
    pg.wait_for_selector("text=Here's what you shared")
    pg.wait_for_timeout(700); pg.evaluate("window.scrollTo(0,0)"); pg.wait_for_timeout(500); pg.screenshot(path=f"{OUT}/{prefix}-08-review.png", full_page=False)
    pg.click("[data-action=submit]"); pg.wait_for_selector("text=All set"); pg.wait_for_timeout(600)
    pg.wait_for_timeout(700); pg.screenshot(path=f"{OUT}/{prefix}-09-thank-you.png", full_page=False)
    rp.click("#refresh"); rp.wait_for_timeout(800); rp.locator("[data-view]").first.click(); rp.wait_for_selector("#detail:not(.hidden)")
    status = rp.inner_text("#detail .status")
    rp.wait_for_timeout(500)
    rp.screenshot(path=f"{OUT}/{prefix}-10-rep-submission.png", full_page=True)
    b.close()
print(json.dumps({"link": link, "rep_status": status, "console_errors": errors}))
